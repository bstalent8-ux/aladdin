CREATE OR REPLACE FUNCTION public.own_product_update(p_product_id uuid, p_expected_version integer, p_name text, p_code text, p_category_code text, p_unit product_unit, p_color_items jsonb DEFAULT '[]'::jsonb, p_weight_kg numeric DEFAULT NULL::numeric, p_size_label text DEFAULT NULL::text, p_brand text DEFAULT NULL::text, p_description text DEFAULT NULL::text, p_base_price numeric DEFAULT NULL::numeric)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_p     public.products;
  v_code  text;
  v_items jsonb;
  v_has_price boolean;
begin
  select * into v_p from public.products where id = p_product_id and deleted_at is null for update;
  if not found then raise exception 'product not found' using errcode = 'P0002'; end if;
  if not app.can_write_publisher(v_p.publisher_id) then
    raise exception 'catalog.write required' using errcode = '42501';
  end if;
  if v_p.version <> p_expected_version then
    raise exception 'product was modified concurrently (expected %, found %)', p_expected_version, v_p.version
      using errcode = '40001';
  end if;
  if v_p.archived_at is not null then
    raise exception 'an archived product must be restored before it can be edited' using errcode = '22023';
  end if;
  v_code := app.own_product_validate(v_p.publisher_id, p_product_id, p_name, p_code, p_category_code, p_unit,
                                     v_p.unit, p_weight_kg, nullif(btrim(p_size_label), ''),
                                     nullif(btrim(p_brand), ''), nullif(btrim(p_description), ''));
  perform app.assert_product_base_price(p_base_price);
  select exists (select 1 from public.product_prices where product_id = p_product_id) into v_has_price;
  -- A product that already has a price keeps one: it can be changed, not blanked.
  if v_has_price and p_base_price is null then
    raise exception 'a product price cannot be removed once it is set' using errcode = '22023';
  end if;
  v_items := app.normalize_product_color_items(p_color_items);
  update public.products set
    name              = btrim(p_name),
    sku               = v_code,
    category_code     = p_category_code,
    unit              = p_unit,
    colors            = app.product_color_names(v_items),
    color_items       = v_items,
    weight_kg         = p_weight_kg,
    size_label        = nullif(btrim(p_size_label), ''),
    brand             = nullif(btrim(p_brand), ''),
    short_description = nullif(btrim(p_description), ''),
    version           = version + 1
  where id = p_product_id;
  if p_base_price is not null then
    insert into public.product_prices (product_id, organization_id, base_price)
    values (p_product_id, v_p.organization_id, p_base_price)
    on conflict (product_id) do update set base_price = excluded.base_price;
  end if;
  perform app.record_audit_event('product.updated', 'product', p_product_id, v_p.organization_id, '{}'::jsonb);
  return v_p.version + 1;
end;
$function$;

CREATE OR REPLACE FUNCTION public.own_product_set_archived(p_product_id uuid, p_archived boolean, p_expected_version integer)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_p public.products;
begin
  select * into v_p from public.products where id = p_product_id and deleted_at is null for update;
  if not found then raise exception 'product not found' using errcode = 'P0002'; end if;
  if not app.can_write_publisher(v_p.publisher_id) then
    raise exception 'catalog.write required' using errcode = '42501';
  end if;
  if v_p.version <> p_expected_version then
    raise exception 'product was modified concurrently' using errcode = '40001';
  end if;
  if (v_p.archived_at is not null) = p_archived then
    return v_p.version;  -- already in the requested state; no-op
  end if;
  update public.products set
    archived_at  = case when p_archived then now() else null end,
    -- Archiving always withdraws the product from the public catalog.
    status       = case when p_archived then 'draft'::public.product_status else status end,
    published_at = case when p_archived then null else published_at end,
    version      = version + 1
  where id = p_product_id;
  perform app.record_audit_event(case when p_archived then 'product.archived' else 'product.restored' end,
    'product', p_product_id, v_p.organization_id, '{}'::jsonb);
  return v_p.version + 1;
end;
$function$;

CREATE OR REPLACE FUNCTION public.set_product_published(p_product_id uuid, p_published boolean, p_expected_version integer)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_p public.products;
begin
  select * into v_p from public.products where id = p_product_id and deleted_at is null for update;
  if not found then raise exception 'product not found'; end if;
  if not app.can_publish_publisher(v_p.publisher_id) then
    raise exception 'catalog.publish required' using errcode = '42501';
  end if;
  if v_p.version <> p_expected_version then
    raise exception 'product was modified concurrently' using errcode = '40001';
  end if;
  if p_published and v_p.archived_at is not null then
    raise exception 'an archived product must be restored before it can be published' using errcode = '22023';
  end if;
  if (v_p.status = 'published') = p_published then
    return v_p.version;
  end if;
  if p_published and not exists (select 1 from public.product_audiences a where a.product_id = p_product_id) then
    raise exception 'select at least one audience before publishing' using errcode = '22023';
  end if;
  update public.products set
    status       = case when p_published then 'published'::public.product_status else 'draft'::public.product_status end,
    published_at = case when p_published then now() else null end,
    version      = version + 1
  where id = p_product_id;
  perform app.record_audit_event(
    case when p_published then 'product.published' else 'product.unpublished' end,
    'product', p_product_id, v_p.organization_id, '{}'::jsonb);
  return v_p.version + 1;
end;
$function$;

CREATE OR REPLACE FUNCTION public.product_audiences_set(p_product_id uuid, p_audiences text[])
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_p public.products;
  v_set text[];
begin
  select * into v_p from public.products where id = p_product_id and deleted_at is null for update;
  if not found then raise exception 'product not found' using errcode = 'P0002'; end if;
  if not app.can_write_publisher(v_p.publisher_id) then
    raise exception 'catalog.write required' using errcode = '42501';
  end if;
  if v_p.archived_at is not null then
    raise exception 'an archived product must be restored before it can be edited' using errcode = '22023';
  end if;
  select coalesce(array_agg(distinct a order by a), '{}') into v_set from unnest(coalesce(p_audiences, '{}')) a;
  if exists (select 1 from unnest(v_set) a where a not in (select code from public.product_audience_types)) then
    raise exception 'unknown audience' using errcode = '22023';
  end if;
  if v_p.status = 'published' and cardinality(v_set) = 0 then
    raise exception 'a published product needs at least one audience' using errcode = '22023';
  end if;
  delete from public.product_audiences where product_id = p_product_id and audience <> all (v_set);
  insert into public.product_audiences (product_id, audience)
  select p_product_id, a from unnest(v_set) a on conflict do nothing;
  perform app.record_audit_event('product.audiences_set', 'product', p_product_id, v_p.organization_id,
    jsonb_build_object('audiences', to_jsonb(v_set)));
end;
$function$;

CREATE OR REPLACE FUNCTION public.product_image_request_upload(p_product_id uuid, p_content_type text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_p    public.products;
  v_ext  text;
  v_pos  smallint;
  v_key  text;
begin
  v_ext := case p_content_type when 'image/jpeg' then 'jpg' when 'image/png' then 'png' when 'image/webp' then 'webp' else null end;
  if v_ext is null then
    raise exception 'unsupported content type' using errcode = '22023';
  end if;
  -- Locking the product row serializes slot allocation, so concurrent requests cannot overfill it.
  select * into v_p from public.products where id = p_product_id and deleted_at is null for update;
  if not found then raise exception 'product not found' using errcode = 'P0002'; end if;
  if not app.can_write_publisher(v_p.publisher_id) then
    raise exception 'catalog.write required' using errcode = '42501';
  end if;
  if v_p.archived_at is not null then
    raise exception 'an archived product must be restored before its images change' using errcode = '22023';
  end if;
  -- An abandoned pending slot does not block the product forever.
  update public.product_images set state = 'deleted'
   where product_id = p_product_id and state = 'pending' and created_at < now() - interval '1 hour';
  select s into v_pos from generate_series(1, 3) s
   where not exists (select 1 from public.product_images i
                      where i.product_id = p_product_id and i.state <> 'deleted' and i.slot = s)
   order by s limit 1;
  if v_pos is null then
    raise exception 'a product can have at most 3 images' using errcode = '23514';
  end if;
  v_key := coalesce(v_p.organization_id, v_p.publisher_id)::text || '/' || p_product_id::text || '/' || extensions.gen_random_uuid()::text || '.' || v_ext;
  insert into public.product_images (product_id, organization_id, object_key, content_type, slot, created_by)
  values (p_product_id, v_p.organization_id, v_key, p_content_type, v_pos, (select auth.uid()));
  return v_key;
end;
$function$;

