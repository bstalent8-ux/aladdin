drop function app.own_product_validate(uuid, uuid, text, text, text, public.product_unit, public.product_unit, numeric, text, text, text);
CREATE OR REPLACE FUNCTION app.own_product_validate(p_publisher_id uuid, p_exclude_id uuid, p_name text, p_code text, p_category_code text, p_unit product_unit, p_prev_unit product_unit, p_weight_kg numeric, p_size_label text, p_brand text, p_description text)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_code text := btrim(regexp_replace(coalesce(p_code, ''), '\s+', ' ', 'g'));
  v_norm text;
begin
  if char_length(btrim(coalesce(p_name, ''))) not between 2 and 160 then
    raise exception 'product name must be 2 to 160 characters' using errcode = '22023';
  end if;
  if char_length(v_code) not between 1 and 60 or v_code ~ '[[:cntrl:]]' then
    raise exception 'product code must be 1 to 60 characters' using errcode = '22023';
  end if;
  if p_category_code is null or not exists (
       select 1 from public.product_categories c where c.code = p_category_code and c.is_active) then
    raise exception 'unknown or inactive product category' using errcode = '22023';
  end if;
  if p_unit is null or not (
       p_unit::text = any (app.showroom_units())
       or p_unit is not distinct from p_prev_unit) then
    raise exception 'unit is not one of the supported product units' using errcode = '22023';
  end if;
  if p_weight_kg is not null and (p_weight_kg < 0 or p_weight_kg > 1000000) then
    raise exception 'weight must be a non-negative number of kilograms' using errcode = '22023';
  end if;
  if p_size_label is not null and char_length(p_size_label) > 80 then
    raise exception 'size is limited to 80 characters' using errcode = '22023';
  end if;
  if p_brand is not null and char_length(p_brand) > 120 then
    raise exception 'brand is limited to 120 characters' using errcode = '22023';
  end if;
  if p_description is not null and char_length(p_description) > 250 then
    raise exception 'description is limited to 250 characters' using errcode = '22023';
  end if;

  v_norm := upper(v_code);
  if exists (
       select 1 from public.products x
        where x.publisher_id = p_publisher_id and x.deleted_at is null
          and x.id is distinct from p_exclude_id
          and (x.code_normalized = v_norm
               or upper(btrim(regexp_replace(coalesce(x.sku, ''), '\s+', ' ', 'g'))) = v_norm)) then
    raise exception 'this product code is already used by this publisher' using errcode = '23505';
  end if;
  return v_code;
end;
$function$;
revoke all on function app.own_product_validate(uuid, uuid, text, text, text, public.product_unit, public.product_unit, numeric, text, text, text) from public, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.own_product_create(p_org_id uuid, p_name text, p_code text, p_category_code text, p_unit product_unit, p_color_items jsonb DEFAULT '[]'::jsonb, p_weight_kg numeric DEFAULT NULL::numeric, p_size_label text DEFAULT NULL::text, p_brand text DEFAULT NULL::text, p_description text DEFAULT NULL::text, p_base_price numeric DEFAULT NULL::numeric)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_id    uuid;
  v_code  text;
  v_items jsonb;
begin
  if not app.is_org_member(p_org_id) then
    raise exception 'not a member of this organization' using errcode = '42501';
  end if;
  if not app.can_write_catalog(p_org_id) then
    raise exception 'catalog.write required' using errcode = '42501';
  end if;
