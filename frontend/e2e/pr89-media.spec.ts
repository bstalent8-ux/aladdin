import { execFileSync } from "node:child_process";
import { mkdirSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { test, expect, devices, type Browser, type BrowserContext, type Page, type TestInfo } from "@playwright/test";
import { E2E_PASSWORD, IDENTITIES } from "./helpers/auth";

/**
 * PR #89 — media delivery smoke on the LOCAL stack (Supabase Storage provider; R2 and the edge Worker
 * stay off, MEDIA_EDGE_DELIVERY_ENABLED unset = false).
 *
 *   1. Avatar: upload through the real crop dialog, the image renders from /api/media/avatar, and the
 *      same URL is 404 for another signed-in user, for a signed-out browser, and for the owner's OLD
 *      cookies replayed after sign-out (the route calls auth.getUser on every read).
 *   2. Product image: upload through the real image manager, the <img> is lazy and async-decoded, and
 *      the same denials hold for /api/media/product.
 *
 * srcset: variants are only generated by providers that store them (R2) and only issued through the
 * edge Worker, so locally the <img> carries no srcset by design; the test records the attribute.
 */

const DB = process.env.E2E_DB_CONTAINER ?? "supabase_db_aladdin";
const SHOTS = process.env.PR89_SCREENSHOT_DIR ?? "/mnt/project-files/showroom-admin/e2e/pr89";
const AXIS = process.env.E2E_LOCALE || process.env.E2E_THEME ? `-${process.env.E2E_LOCALE ?? "en"}-${process.env.E2E_THEME ?? "light"}` : "";
const HANA_ORG = "9c000000-cccc-4ccc-8ccc-000000000001";
const TURNSTILE_STUB =
  'window.turnstile={render:function(el,o){setTimeout(function(){o.callback("XXXX.DUMMY.TOKEN.XXXX")},0);return "local-test"},remove:function(){},reset:function(){}};';

test.describe.configure({ mode: "serial" });

function scalar(sql: string): string {
  return execFileSync("docker", ["exec", "-i", DB, "psql", "-U", "postgres", "-d", "postgres", "-tA", "-c", sql]).toString().trim();
}

const isMobile = (info: TestInfo) => info.project.name.includes("mobile");

async function newContext(browser: Browser, info: TestInfo): Promise<BrowserContext> {
  const baseURL = String(info.project.use.baseURL);
  const ctx = await browser.newContext(
    isMobile(info) ? { ...devices["Pixel 5"], viewport: { width: 390, height: 844 }, baseURL } : { viewport: { width: 1440, height: 900 }, baseURL },
  );
  await ctx.route("https://challenges.cloudflare.com/turnstile/v0/api.js*", (route) =>
    route.fulfill({ contentType: "application/javascript", body: TURNSTILE_STUB }),
  );
  return ctx;
}

async function signIn(page: Page, email: string): Promise<void> {
  await page.goto("/auth/sign-in");
  await page.getByLabel(/^email address$|^البريد الإلكتروني$/i).fill(email);
  await page.getByLabel(/^password$|^كلمة المرور$/i).fill(E2E_PASSWORD);
  await expect(page.locator('input[name="captchaToken"]')).not.toHaveValue("", { timeout: 15_000 });
  await page.getByRole("button", { name: /^sign in$|^تسجيل الدخول$/i }).click();
  await page.waitForURL((url) => !url.pathname.startsWith("/auth"), { waitUntil: "commit", timeout: 30_000 });
}

async function signOut(page: Page): Promise<void> {
  await page.getByTestId("profile-menu-trigger").filter({ visible: true }).first().click();
  await page.getByTestId("profile-sign-out").filter({ visible: true }).first().click();
  await page.waitForURL(/\/(auth|showroom|installer)\/sign-in/, { waitUntil: "commit" });
}

async function testImage(width: number, height: number): Promise<Buffer> {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
    <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#b3541e"/><stop offset="1" stop-color="#1e6fb3"/></linearGradient></defs>
    <rect width="100%" height="100%" fill="url(#g)"/><circle cx="${width / 2}" cy="${height / 2}" r="${Math.min(width, height) / 4}" fill="#f4efe6"/></svg>`;
  return sharp(Buffer.from(svg)).png().toBuffer();
}

/** Status of a GET for `url` with exactly the given cookies (none = signed out). */
async function statusWith(browser: Browser, info: TestInfo, url: string, cookies: Parameters<BrowserContext["addCookies"]>[0]): Promise<number> {
  const ctx = await browser.newContext({ baseURL: String(info.project.use.baseURL) });
  if (cookies.length) await ctx.addCookies(cookies);
  const res = await ctx.request.get(url, { maxRedirects: 0 });
  await ctx.close();
  return res.status();
}

async function imageRendered(page: Page, selector: string): Promise<void> {
  await expect
    .poll(() => page.locator(selector).first().evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0), { timeout: 20_000 })
    .toBe(true);
}

test("PR #89 avatar: upload renders from /api/media and is private to the owner's live session", async ({ browser }, info) => {
  mkdirSync(SHOTS, { recursive: true });
  const device = isMobile(info) ? "mobile" : "desktop";
  const owner = await newContext(browser, info);
  const page = await owner.newPage();
  await signIn(page, IDENTITIES.consumer);
  await page.goto("/settings/profile");
  // A previous run may have left an avatar: wait for the NEW one, not the old (now deleted) object.
  const previous = await page.getByTestId("avatar-current").getAttribute("src", { timeout: 2_000 }).catch(() => null);
  await page.getByTestId("avatar-input").setInputFiles({ name: "avatar.png", mimeType: "image/png", buffer: await testImage(800, 800) });
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByTestId("avatar-cropper")).toBeVisible();
  await dialog.getByRole("button", { name: /^save|^حفظ/i }).click();
  await expect(dialog).toHaveCount(0, { timeout: 30_000 });
  const img = page.getByTestId("avatar-current");
  await expect(img).toBeVisible({ timeout: 20_000 });
  if (previous) await expect(img).not.toHaveAttribute("src", previous, { timeout: 20_000 });
  await imageRendered(page, '[data-testid="avatar-current"]');
  const src = (await img.getAttribute("src"))!;
  expect(src).toMatch(/^\/api\/media\/avatar\?key=/);
  info.annotations.push({ type: "avatar img", description: `src=${src} srcset=${await img.getAttribute("srcset")} loading=${await img.getAttribute("loading")}` });
  await page.screenshot({ path: path.join(SHOTS, `avatar-${device}${AXIS}.png`), fullPage: true });

  const ownerRes = await owner.request.get(src);
  expect(ownerRes.status()).toBe(200);
  expect(ownerRes.headers()["content-type"]).toMatch(/^image\//);
  expect(ownerRes.headers()["cache-control"]).toContain("no-store");

  // A different signed-in user.
  const other = await newContext(browser, info);
  const otherPage = await other.newPage();
  await signIn(otherPage, IDENTITIES.manager);
  expect((await other.request.get(src)).status(), "another user").toBe(404);
  await other.close();

  // Signed out (no cookies), then the owner's own cookies replayed after a real sign-out.
  expect(await statusWith(browser, info, src, []), "no session").toBe(404);
  const before = await owner.cookies();
  await signOut(page);
  expect((await owner.request.get(src)).status(), "same browser after sign-out").toBe(404);
  expect(await statusWith(browser, info, src, before), "pre-sign-out cookies replayed").toBe(404);
  await owner.close();
});

test("PR #89 product image: upload renders lazily from /api/media and is denied outside the workspace", async ({ browser }, info) => {
  mkdirSync(SHOTS, { recursive: true });
  const device = isMobile(info) ? "mobile" : "desktop";
  const productId = scalar(`
select p.id from public.products p
 where p.organization_id = '${HANA_ORG}'
   and (select count(*) from public.product_images i where i.product_id = p.id and i.state <> 'deleted') < 3
 order by p.id limit 1`);
  expect(productId, "a Hana product with a free image slot").not.toBe("");

  const owner = await newContext(browser, info);
  const page = await owner.newPage();
  await signIn(page, IDENTITIES.showroom);
  await page.goto(`/showroom/my-products/${productId}/edit`);
  const manager = page.getByTestId("image-manager");
  await expect(manager).toBeVisible();
  const before = await manager.locator("img").count();
  await page.getByTestId("image-input").setInputFiles({ name: "tile.png", mimeType: "image/png", buffer: await testImage(1600, 1200) });
  await expect(manager.locator("img")).toHaveCount(before + 1, { timeout: 45_000 });
  const img = manager.locator("img").last();
  await img.scrollIntoViewIfNeeded();
  await expect.poll(() => img.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0), { timeout: 20_000 }).toBe(true);
  const src = (await img.getAttribute("src"))!;
  // The owner's own product: no viewer workspace parameter (that is added for other workspaces' catalogs).
  expect(src).toMatch(/^\/api\/media\/product\?key=[^&]+$/);
  await expect(img).toHaveAttribute("loading", "lazy");
  await expect(img).toHaveAttribute("decoding", "async");
  const srcset = await img.getAttribute("srcset");
  info.annotations.push({ type: "product img", description: `src=${src} srcset=${srcset} sizes=${await img.getAttribute("sizes")}` });
  // Local provider = Supabase: no stored variants, so no srcset (variants are R2 + edge only).
  expect(srcset).toBeNull();
  await page.screenshot({ path: path.join(SHOTS, `product-image-${device}${AXIS}.png`), fullPage: true });

  const ownerRes = await owner.request.get(src);
  expect(ownerRes.status()).toBe(200);
  expect(ownerRes.headers()["content-type"]).toMatch(/^image\//);

  // The seeded product targets every audience, so a consumer may legitimately see its photo. Narrow the
  // audience to Supplier for this check (local test DB only) so the consumer is outside it, then restore.
  const other = await newContext(browser, info);
  const otherPage = await other.newPage();
  await signIn(otherPage, IDENTITIES.consumer);
  expect((await other.request.get(src)).status(), "a targeted consumer").toBe(200);
  const audiences = scalar(`select string_agg(audience, ',') from public.product_audiences where product_id = '${productId}'`);
  scalar(`delete from public.product_audiences where product_id = '${productId}' and audience <> 'supplier'`);
  try {
    expect((await other.request.get(src)).status(), "a user outside the product's audience and the workspace").toBe(404);
  } finally {
    scalar(`insert into public.product_audiences (product_id, audience)
            select '${productId}', unnest(string_to_array('${audiences}', ',')) on conflict do nothing`);
  }
  await other.close();

  expect(await statusWith(browser, info, src, []), "no session").toBe(404);
  const cookies = await owner.cookies();
  await signOut(page);
  expect(await statusWith(browser, info, src, cookies), "pre-sign-out cookies replayed").toBe(404);
  await owner.close();
});
